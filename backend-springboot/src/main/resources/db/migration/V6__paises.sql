-- Catálogo de países administrable (alta/baja/modificación desde el panel de administración).
-- Incluye metadatos para parametrizar el teléfono: código ISO (alpha-2) y prefijo telefónico.

CREATE TABLE IF NOT EXISTS pais (
    id_pais BIGSERIAL PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL,
    codigo_iso VARCHAR(2),
    prefijo_telefonico VARCHAR(6),
    estado BOOLEAN NOT NULL DEFAULT TRUE
);

-- La tabla podría existir de antes (creada por ddl-auto) sin las columnas nuevas.
ALTER TABLE pais ADD COLUMN IF NOT EXISTS codigo_iso VARCHAR(2);
ALTER TABLE pais ADD COLUMN IF NOT EXISTS prefijo_telefonico VARCHAR(6);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uk_pais_nombre'
    ) THEN
        ALTER TABLE pais ADD CONSTRAINT uk_pais_nombre UNIQUE (nombre);
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uk_pais_codigo_iso'
    ) THEN
        ALTER TABLE pais ADD CONSTRAINT uk_pais_codigo_iso UNIQUE (codigo_iso);
    END IF;
END $$;

